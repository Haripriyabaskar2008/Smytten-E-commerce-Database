1. Combining multiple tables
1.1 Customer and Orders — INNER JOIN
SELECT C.CUSTOMER_ID,
C.CUSTOMER_NAME,
O.ORDER_ID,
O.ORDER_DATE,
O.TOTAL_AMOUNT,
O.ORDER_STATUS
FROM CUSTOMER2 C
INNER JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
ORDER BY O.ORDER_ID;


1.2 Orders and Payment — INNER JOIN
SELECT O.ORDER_ID,
O.CUSTOMER_ID,
O.ORDER_DATE,
O.TOTAL_AMOUNT,
P.PAYMENT_ID,
P.PAYMENT_METHOD,
P.PAYMENT_STATUS,
P.AMOUNT
FROM ORDERS O
INNER JOIN PAYMENT P
ON O.ORDER_ID = P.ORDER_ID
ORDER BY O.ORDER_ID;


1.3 Product and Order Details — INNER JOIN
SELECT P.PRODUCT_ID,
P.PRODUCT_NAME,
P.PRICE,
OD.ORDER_ID,
OD.QUANTITY,
OD.PRICE AS UNIT_PRICE
FROM PRODUCT2 P
INNER JOIN ORDER_DETAILS OD
ON P.PRODUCT_ID = OD.PRODUCT_ID
ORDER BY OD.ORDER_ID;

2. LEFT JOIN
2.1 Display all customers and their orders
SELECT C.CUSTOMER_ID,
C.CUSTOMER_NAME,
O.ORDER_ID,
O.ORDER_DATE,
O.TOTAL_AMOUNT,
O.ORDER_STATUS
FROM CUSTOMER2 C
LEFT JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
ORDER BY C.CUSTOMER_ID;

3. RIGHT JOIN
3.1 Display all orders and customer details
SELECT O.ORDER_ID,
O.ORDER_DATE,
O.TOTAL_AMOUNT,
O.ORDER_STATUS,
C.CUSTOMER_ID,
C.CUSTOMER_NAME,
C.EMAIL
FROM CUSTOMER2 C
RIGHT JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
ORDER BY O.ORDER_ID;

4. Complete order details
This query combines CUSTOMER2, ORDERS, ORDER_DETAILS, PRODUCT2 and PAYMENT.
SELECT C.CUSTOMER_ID,
C.CUSTOMER_NAME,
O.ORDER_ID,
O.ORDER_DATE,
P.PRODUCT_ID,
P.PRODUCT_NAME,
OD.QUANTITY,
OD.PRICE AS UNIT_PRICE,
OD.QUANTITY * OD.PRICE AS ITEM_TOTAL,
O.TOTAL_AMOUNT,
O.ORDER_STATUS,
PY.PAYMENT_METHOD,
PY.PAYMENT_STATUS
FROM CUSTOMER2 C
INNER JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
INNER JOIN ORDER_DETAILS OD
ON O.ORDER_ID = OD.ORDER_ID
INNER JOIN PRODUCT2 P
ON OD.PRODUCT_ID = P.PRODUCT_ID
LEFT JOIN PAYMENT PY
ON O.ORDER_ID = PY.ORDER_ID
ORDER BY O.ORDER_ID;

5. Customer purchase history
SELECT C.CUSTOMER_ID,
C.CUSTOMER_NAME,
O.ORDER_ID,
O.ORDER_DATE,
P.PRODUCT_NAME,
OD.QUANTITY,
OD.PRICE,
O.TOTAL_AMOUNT
