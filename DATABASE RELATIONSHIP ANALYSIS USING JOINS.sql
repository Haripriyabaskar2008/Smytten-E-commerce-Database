7. Multi-table business report
SELECT C.CUSTOMER_NAME,
P.PRODUCT_NAME,
SUM(OD.QUANTITY) AS TOTAL_QUANTITY,
SUM(OD.QUANTITY * OD.PRICE) AS PRODUCT_SALES_AMOUNT
FROM CUSTOMER2 C
INNER JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
INNER JOIN ORDER_DETAILS OD
ON O.ORDER_ID = OD.ORDER_ID
INNER JOIN PRODUCT2 P
ON OD.PRODUCT_ID = P.PRODUCT_ID
GROUP BY C.CUSTOMER_NAME, P.PRODUCT_NAME
ORDER BY PRODUCT_SALES_AMOUNT DESC;

8. Payment transaction report
SELECT PY.PAYMENT_ID,
O.ORDER_ID,
C.CUSTOMER_NAME,
PY.PAYMENT_METHOD,
PY.PAYMENT_DATE,
PY.AMOUNT,
PY.PAYMENT_STATUS
FROM PAYMENT PY
INNER JOIN ORDERS O
ON PY.ORDER_ID = O.ORDER_ID
INNER JOIN CUSTOMER2 C
ON O.CUSTOMER_ID = C.CUSTOMER_ID
ORDER BY PY.PAYMENT_DATE DESC;



