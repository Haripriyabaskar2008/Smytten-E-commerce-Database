-- SMYTTEN E-COMMERCE DATABASE - ORDERS AND ORDER_DETAILS

CREATE TABLE ORDERS (
    ORDER_ID NUMBER PRIMARY KEY,
    CUSTOMER_ID NUMBER NOT NULL,
    ORDER_DATE DATE DEFAULT SYSDATE,
    TOTAL_AMOUNT NUMBER(10,2),
    ORDER_STATUS VARCHAR2(30)
);

ALTER TABLE ORDERS
ADD CONSTRAINT FK_ORDERS_CUSTOMER
FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER2(CUSTOMER_ID);

CREATE TABLE ORDER_DETAILS (
    ORDER_DETAIL_ID NUMBER PRIMARY KEY,
    ORDER_ID NUMBER NOT NULL,
    PRODUCT_ID NUMBER NOT NULL,
    QUANTITY NUMBER NOT NULL CHECK (QUANTITY > 0),
    PRICE NUMBER(10,2) NOT NULL
);

ALTER TABLE ORDER_DETAILS
ADD CONSTRAINT FK_ORDER_DETAILS_ORDER
FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ORDER_ID);

ALTER TABLE ORDER_DETAILS
ADD CONSTRAINT FK_ORDER_DETAILS_PRODUCT
FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT2(PRODUCT_ID);

