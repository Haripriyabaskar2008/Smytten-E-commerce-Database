-- 9. SELLER PRODUCT INFORMATION

SELECT
    S.SELLER_ID,
    S.SELLER_NAME,
    I.PRODUCT_ID,
    I.AVAILABLE_STOCK,
    I.PRODUCT_STATUS
FROM SELLER S
JOIN INVENTORY I
ON S.SELLER_ID = I.SELLER_ID;


-- 10. INVENTORY STATUS REPORT

SELECT
    I.INVENTORY_ID,
    S.SELLER_NAME,
    I.PRODUCT_ID,
    I.AVAILABLE_STOCK,
    I.PRODUCT_STATUS,
    I.LAST_UPDATED
FROM INVENTORY I
JOIN SELLER S
ON I.SELLER_ID = S.SELLER_ID
ORDER BY I.PRODUCT_STATUS, I.PRODUCT_ID;


