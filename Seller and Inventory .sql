-- 3. CREATE INVENTORY TABLE

CREATE TABLE INVENTORY (
    INVENTORY_ID NUMBER PRIMARY KEY,
    SELLER_ID NUMBER NOT NULL,
    PRODUCT_ID NUMBER NOT NULL,
    AVAILABLE_STOCK NUMBER NOT NULL
        CHECK (AVAILABLE_STOCK >= 0),
    LAST_UPDATED DATE DEFAULT SYSDATE,
    PRODUCT_STATUS VARCHAR2(20) NOT NULL
);


-- 4. ESTABLISH RELATIONSHIP WITH SELLER

ALTER TABLE INVENTORY
ADD CONSTRAINT FK_INVENTORY_SELLER
FOREIGN KEY (SELLER_ID)
REFERENCES SELLER(SELLER_ID);


-- 5. ESTABLISH RELATIONSHIP WITH PRODUCT

ALTER TABLE INVENTORY
ADD CONSTRAINT FK_INVENTORY_PRODUCT
FOREIGN KEY (PRODUCT_ID)
REFERENCES PRODUCT2(PRODUCT_ID);


