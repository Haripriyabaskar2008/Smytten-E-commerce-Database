REVIEW TABLE:
  
CREATE TABLE REVIEW (
REVIEW_ID NUMBER PRIMARY KEY,
CUSTOMER_ID NUMBER NOT NULL,
PRODUCT_ID NUMBER NOT NULL,
REVIEW_TEXT VARCHAR2(500),
REVIEW_DATE DATE DEFAULT SYSDATE,
CONSTRAINT FK_REVIEW_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER2(CUSTOMER_ID),
CONSTRAINT FK_REVIEW_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT2(PRODUCT_ID)
);
RATING TABLE:
  
CREATE TABLE RATING (
RATING_ID NUMBER PRIMARY KEY,
CUSTOMER_ID NUMBER NOT NULL,
PRODUCT_ID NUMBER NOT NULL,
RATING NUMBER(1) NOT NULL CHECK (RATING BETWEEN 1 AND 5),
RATING_DATE DATE DEFAULT SYSDATE,
CONSTRAINT FK_RATING_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER2(CUSTOMER_ID),
CONSTRAINT FK_RATING_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT2(PRODUCT_ID)
);
