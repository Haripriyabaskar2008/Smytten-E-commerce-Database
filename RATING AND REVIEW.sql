DISPLAY ALL REVIEW:
  
SELECT REVIEW_ID,CUSTOMER_ID,PRODUCT_ID,REVIEW_TEXT,REVIEW_DATE
FROM REVIEW
ORDER BY REVIEW_DATE;

DSIPLAY ALL RATING:
SELECT RATING_ID,CUSTOMER_ID,PRODUCT_ID,RATING,RATING_DATE
FROM RATING
ORDER BY RATING_DATE;

Calculate average product rating:
SELECT PRODUCT_ID,
COUNT(RATING) AS TOTAL_RATINGS,
ROUND(AVG(RATING),2) AS AVERAGE_RATING
FROM RATING
GROUP BY PRODUCT_ID
ORDER BY AVERAGE_RATING DESC;

Identify highly rated products:
SELECT PRODUCT_ID,
ROUND(AVG(RATING),2) AS AVERAGE_RATING
FROM RATING
GROUP BY PRODUCT_ID
HAVING AVG(RATING) >= 4
ORDER BY AVERAGE_RATING DESC;



